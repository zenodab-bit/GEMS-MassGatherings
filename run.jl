# ===========================================================================
# run.jl
#
# Run this file to run a simulation: julia -t 8 run.jl (from this folder).
# It loads the MassGatherings package (the code in src/) and
# config/user_config.jl (the events), then calls run_scenario, or
# run_comparison / run_sweep, which sample the events and the population,
# run GEMS, then analyse, save and (optionally) validate the results.
#
# The settings below (n_simulations, run_validation, the comparison and
# sweep, and the population files) are the main things to adjust here;
# everything else you'd want to change lives in config/user_config.jl.
# ===========================================================================

ENV["GKSwstype"] = "100"   # headless plotting backend; must be set before Plots loads

import Pkg
Pkg.activate(@__DIR__)

using MassGatherings
using Distributions   # for transmission_dist (e.g. Gamma) in config/user_config.jl

include("config/user_config.jl")

# === Run ===
n_simulations = 3
run_validation = true
# What each replicate draws for itself instead of sharing one draw (the
# events themselves always stay the same):
#   []                            - nothing: one setup for all replicates (default)
#   [:attendance]                 - who attends which event
#   [:transmission]               - everyone's transmission_prob
#   [:attendance, :transmission]  - both
vary_per_replicate = []

# Branching: every replicate (a "history") runs n_futures times, identical
# up to day branch_day - 1, each with its own random numbers from
# branch_day on. Future 1 is the history's own continuation, as without
# branching. branch_day = nothing: no branching.
branch_day = nothing
n_futures = 1
# Which replicates to run, by number: nothing for all (1 to n_simulations),
# or e.g. [7] to rerun replicate 7 of an earlier run exactly (with that
# run's gems_seed and settings, see README "Rerunning a run"), e.g. to
# branch it.
histories = nothing
# true: run the scenario twice, with and without its events (same seeds),
# and compare the two (comparison.txt / .png). Takes twice as long.
compare_without_events = false

# Sweep: runs the comparison above once per value in sweep_values, to see
# how the events' effect depends on one setting (sweep.txt / .png). `sweep`
# says what changes for each value; anything it doesn't return stays as set
# here and in config/user_config.jl. sweep_values = nothing: no sweep.
# Pick one of the two blocks below (or write your own):
sweep_values = nothing

# 1. When the festival (category 1, one draw) happens. Only the event
#    changes, so the run without events runs once for all values.
# sweep_values = [10, 20, 30, 40, 50, 60, 70]
sweep_label = "event day"
sweep(day) = (; event_config = with_date(event_config, 1, day))

# 2. The average transmission probability (std kept at 0.1, as in
#    config/user_config.jl). This changes the whole epidemic, so every value gets
#    its own run without events: twice the runs of sweep 1.
# sweep_values = [0.2, 0.25, 0.3, 0.35, 0.4]
# sweep_label = "mean transmission"
# sweep(m) = (; transmission_dist = Gamma(gamma_params(m, 0.1)...))

# Base population.
#   nothing (the default): a synthetic population generated by GEMS, with
#   the settings in `synthetic` (n = size; also avg_household_size,
#   avg_office_size, avg_school_size). Good for trying things out, but not
#   representative of a real place.
#   For realistic results, your own population: a .jld2 file holding a table
#   under "data", with at least id, age, sex (1 or 2) and the GEMS setting
#   ids (household, and optionally office, schoolclass, municipality), like
#   the GEMS population files, e.g. joinpath(@__DIR__, "data", "people_X.jld2").
#   No population is shipped with the code. To keep your own settings out of
#   git, use a copy of this file named my_*.jl (see README).
population_file = nothing
synthetic = (; n = 100_000)
# The population file's matching GEMS settings file (adds e.g. household
# coordinates, region codes and schools/workplaces), or nothing. With a
# settings file, runs are slower (see README).
settings_file = nothing

scenario = (;
    transmission_dist,
    configfile,
    population = population_file,
    synthetic,
    settings_file,
    n_simulations,
    gems_seed,
    run_validation,
    vary_per_replicate,
    branch_day,
    n_futures,
    histories,
    # copied into run_info/: the config, this script (under its own name) and the TOML
    run_info_files = [joinpath(@__DIR__, "config", "user_config.jl"), @__FILE__, configfile],
    results_dir = joinpath(@__DIR__, "Results"),   # results go next to this file
    run_info = (; population_file))

results = if !isnothing(sweep_values)
    run_sweep(event_config; scenario..., sweep, sweep_values, sweep_label)
elseif compare_without_events
    run_comparison(event_config; scenario...)
else
    run_scenario(event_config; scenario...)
end


println("End run")
